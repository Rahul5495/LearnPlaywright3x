//operator compares two values and always returns a boolean (true or false)

// == is Loose comparison (checks the value only, ignores the data type)
console.log(5=="5");

// === is Strict comparison (checks the value AND the data type)
console.log(5==="5");

// != is Loose comparison
console.log(3!="3");

// !== is Strict comparison
console.log(6!=="6");

console.log(4<5);
console.log(4>5);
console.log(4>=4);
console.log(4<=4);