
let arr= [12,45,14,24,67,87];
console.log(arr);

// Add to END
arr.push(4);
console.log(arr);

//remove from END
arr.pop();
console.log(arr);

arr.push(23, 22);
console.log(arr);

// Add to beginning
arr.unshift(10);
console.log(arr);

// Remove from beginning
arr.shift();
console.log(arr);

arr.splice(2, 1);
console.log(arr);

arr.splice(2, 2);
console.log(arr);

arr.splice(2, 0, 99);
console.log(arr);

arr.splice(1,2,10,20);
console.log(arr);

